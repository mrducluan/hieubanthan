/** Tách chữ có {biến} thành các đoạn chữ (đoạn rỗng bỏ): React dựng mỗi đoạn là một nút chữ riêng — đúng như JSX cũ
 *  `Tuổi {x} làm nhà` (HTML bản Việt giữ nguyên cả dấu ngăn `<!-- -->` giữa các nút chữ). Biến không có giữ nguyên. */
export function tachBien(s: string, bien: Readonly<Record<string, string | number>> = {}): string[] {
  const ra: string[] = [];
  let i = 0;
  for (const mt of s.matchAll(/\{([a-z_]+)\}/g)) {
    if (mt.index! > i) ra.push(s.slice(i, mt.index));
    ra.push(Object.hasOwn(bien, mt[1]!) ? String(bien[mt[1]!]) : mt[0]);
    i = mt.index! + mt[0].length;
  }
  if (i < s.length) ra.push(s.slice(i));
  return ra.filter((x) => x !== "");
}

/** Bộ đọc chữ của các trang năm & tuổi theo ngôn ngữ: `c(khoá, biến)` → một chuỗi; `p(khoá, biến)` → các đoạn (xem `tachBien`). */
export function chuNamTuoi(ngonNgu: "vi" | "en") {
  const c = taoChu(CHU_NAM_TUOI_UI, null, ngonNgu);
  const p = (k: keyof typeof CHU_NAM_TUOI_UI, bien: Readonly<Record<string, string | number>> = {}) => tachBien(c(k), bien);
  return { c: (k: keyof typeof CHU_NAM_TUOI_UI, bien?: Readonly<Record<string, string | number>>) => c(k, bien && Object.fromEntries(Object.entries(bien).map(([a, b]) => [a, String(b)]))), p, en: ngonNgu === "en" };
}
export type ChuNamTuoi = ReturnType<typeof chuNamTuoi>;

/** Link nội bộ trên trang chạy hai ngôn ngữ: bản Việt → nguyên đường dẫn; bản Anh → URL Anh nếu trang đã mở, chưa mở → null
 *  (ẩn link — trang Anh không trỏ sang trang Việt). */
export const lienNN = (en: boolean, duongVi: string): string | null => (en ? banAnh(duongVi) : duongVi);

/** Ngày hiển thị: bản Việt "dd/mm/yyyy" như cũ; bản Anh theo Intl ("6 Feb 2027"). */
export const ngayNN = (en: boolean, iso: string) => (en ? dinhNgay(iso, "en", "ngan") : iso.split("-").reverse().join("/"));
